function generateAllBlogPosts(count) {
  const posts = [];
  for (let i = 0; i < count; i++) {
    const basePost = allBlogData[i % allBlogData.length];
    
    posts.push({
      ...basePost,
      slug: basePost.slug,
      title: basePost.title,
      excerpt: `Explore ${basePost.title.toLowerCase()}. Learn how to improve comfort and save money with expert insights on ${basePost.keywords.split(',')[0]}.`,
      content: generateBlogContent(basePost),
      blogSchema: {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": basePost.title,
        "description": `An in-depth guide to ${basePost.keywords.split(',')[0]}. Learn about the benefits, costs, and top brands like ${basePost.brandMentions}.`,
        "datePublished": basePost.date,
        "author": { "@type": "Organization", "name": "Arizona House of Film" },
        "image": `https://arizonahouseoffilm.com/og-image-${basePost.slug}.jpg`,
        "mainEntityOfPage": {
          "@type": "WebPage",
          "@id": `https://arizonahouseoffilm.com/blog/${basePost.slug}`
        },
        "publisher": {
          "@type": "Organization",
          "name": "Arizona House of Film",
          "logo": {
            "@type": "ImageObject",
            "url": "https://arizonahouseoffilm.com/favicon-512.png",
            "width": 512,
            "height": 512
          }
        }
      },
      faqPageSchema: {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": basePost.faqs.map(faq => ({
          "@type": "Question",
          "name": faq.question,
          "acceptedAnswer": {
            "@type": "Answer",
            "text": faq.answer
          }
        }))
      }
    });
  }
  
  const uniquePosts = Array.from(new Map(posts.map(post => [post.slug, post])).values());
  return uniquePosts;
}

